-- Execute as ARI_DEPLOY. Embeddings are reproducible from the historical source reports.
CREATE COLUMN TABLE ARI.REPAIR_REPORT_EMBEDDINGS (
    ID NVARCHAR(36) NOT NULL,
    REPAIR_ORDER_ID NVARCHAR(36) NOT NULL,
    CHUNK_INDEX INTEGER NOT NULL,
    EMBEDDING REAL_VECTOR(1536) NOT NULL,
    EMBEDDING_MODEL NVARCHAR(100) NOT NULL,
    MODEL_VERSION NVARCHAR(100) NOT NULL,
    SOURCE_SHA256 NVARCHAR(64) NOT NULL,
    SOURCE_AVAILABLE_AT_UTC TIMESTAMP NOT NULL,
    CREATED_AT_UTC TIMESTAMP NOT NULL,
    CONSTRAINT PK_REPAIR_REPORT_EMBEDDINGS PRIMARY KEY (ID),
    CONSTRAINT FK_REPAIR_REPORT_EMBEDDINGS_ORDER FOREIGN KEY (REPAIR_ORDER_ID)
        REFERENCES ARI.REPAIR_ORDERS (ID) ON DELETE RESTRICT,
    CONSTRAINT UQ_REPAIR_REPORT_EMBEDDING_SOURCE UNIQUE
        (REPAIR_ORDER_ID, CHUNK_INDEX, EMBEDDING_MODEL, MODEL_VERSION),
    CONSTRAINT CK_REPAIR_REPORT_EMBEDDING_CHUNK CHECK (CHUNK_INDEX >= 0)
)
--#STATEMENT
CREATE INDEX IX_REPAIR_REPORT_EMBEDDINGS_MODEL
    ON ARI.REPAIR_REPORT_EMBEDDINGS (EMBEDDING_MODEL, MODEL_VERSION, SOURCE_AVAILABLE_AT_UTC)
--#STATEMENT
GRANT SELECT, INSERT, UPDATE, DELETE ON ARI.REPAIR_REPORT_EMBEDDINGS TO ARI_APP
