CREATE INDEX IX_REPAIR_COMPLICATIONS_EXECUTION ON ARI.REPAIR_COMPLICATIONS (REPAIR_EXECUTION_ID)
--#STATEMENT
CREATE INDEX IX_REPAIR_COMPLICATIONS_CODE ON ARI.REPAIR_COMPLICATIONS (COMPLICATION_CODE)
--#STATEMENT
CREATE COLUMN TABLE ARI.REPAIR_CONDITIONS (
