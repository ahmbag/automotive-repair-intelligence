-- ARI-DATA-01 / migration 002
-- Historical repair outcomes remain relationally and temporally distinct from pre-repair facts.
CREATE COLUMN TABLE ARI.HISTORICAL_DATASETS (
    DATASET_ID NVARCHAR(100) NOT NULL,
    GENERATOR_VERSION NVARCHAR(30) NOT NULL,
    SEED INTEGER NOT NULL,
    EXPECTED_RECORD_COUNT INTEGER NOT NULL,
    IMPORTED_RECORD_COUNT INTEGER NOT NULL DEFAULT 0,
    DATA_CLASSIFICATION NVARCHAR(20) NOT NULL,
    SCHEMA_VERSION INTEGER NOT NULL,
    CHECKSUM NVARCHAR(64) NOT NULL,
    IMPORT_STATUS NVARCHAR(20) NOT NULL,
    IMPORTED_AT_UTC TIMESTAMP NULL,
    CONSTRAINT PK_HISTORICAL_DATASETS PRIMARY KEY (DATASET_ID),
    CONSTRAINT CK_DATASET_COUNTS CHECK (
        EXPECTED_RECORD_COUNT > 0 AND IMPORTED_RECORD_COUNT >= 0
        AND IMPORTED_RECORD_COUNT <= EXPECTED_RECORD_COUNT),
    CONSTRAINT CK_DATASET_CLASSIFICATION CHECK (DATA_CLASSIFICATION = 'SYNTHETIC'),
    CONSTRAINT CK_DATASET_STATUS CHECK (IMPORT_STATUS IN ('IMPORTING', 'COMPLETE'))
)
