CREATE COLUMN TABLE ARI.REPAIR_OPERATIONS (
    ID NVARCHAR(36) NOT NULL,
    REPAIR_ORDER_ID NVARCHAR(36) NOT NULL,
    ASSEMBLY_CODE NVARCHAR(100) NOT NULL,
    OPERATION_CODE NVARCHAR(100) NOT NULL,
    REFERENCE_LABOR_HOURS DECIMAL(7,2) NOT NULL,
    SEQUENCE_NUMBER INTEGER NOT NULL,
    CONSTRAINT PK_REPAIR_OPERATIONS PRIMARY KEY (ID),
    CONSTRAINT FK_REPAIR_OPERATIONS_ORDER FOREIGN KEY (REPAIR_ORDER_ID)
        REFERENCES ARI.REPAIR_ORDERS (ID) ON DELETE RESTRICT,
    CONSTRAINT CK_OPERATION_REFERENCE CHECK (REFERENCE_LABOR_HOURS > 0),
    CONSTRAINT UQ_REPAIR_OPERATION_SEQUENCE UNIQUE (REPAIR_ORDER_ID, SEQUENCE_NUMBER)
)
--#STATEMENT
CREATE INDEX IX_REPAIR_OPERATIONS_ORDER ON ARI.REPAIR_OPERATIONS (REPAIR_ORDER_ID)
--#STATEMENT
CREATE COLUMN TABLE ARI.REPAIR_EXECUTIONS (
    ID NVARCHAR(36) NOT NULL,
    REPAIR_ORDER_ID NVARCHAR(36) NOT NULL,
    ACTUAL_LABOR_MINUTES INTEGER NOT NULL,
    STARTED_AT_UTC TIMESTAMP NOT NULL,
    COMPLETED_AT_UTC TIMESTAMP NOT NULL,
    PERFORMED_OPERATION_CODES_JSON NVARCHAR(5000) NOT NULL,
    REPAIR_REPORT NVARCHAR(5000) NOT NULL,
    CONSTRAINT PK_REPAIR_EXECUTIONS PRIMARY KEY (ID),
    CONSTRAINT FK_REPAIR_EXECUTIONS_ORDER FOREIGN KEY (REPAIR_ORDER_ID)
        REFERENCES ARI.REPAIR_ORDERS (ID) ON DELETE RESTRICT,
    CONSTRAINT UQ_REPAIR_EXECUTION_ORDER UNIQUE (REPAIR_ORDER_ID),
    CONSTRAINT CK_EXECUTION_LABOR CHECK (ACTUAL_LABOR_MINUTES > 0),
    CONSTRAINT CK_EXECUTION_TIME CHECK (STARTED_AT_UTC <= COMPLETED_AT_UTC)
)
--#STATEMENT
CREATE INDEX IX_REPAIR_EXECUTIONS_COMPLETED ON ARI.REPAIR_EXECUTIONS (COMPLETED_AT_UTC)
--#STATEMENT
CREATE COLUMN TABLE ARI.REPAIR_COMPLICATIONS (
